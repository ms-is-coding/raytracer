static void draw_text_at(t_ui_ctx *ui, int32_t x, int32_t y,
                          const char *text, uint32_t color) {
  while (*text) {
    unsigned char c = (unsigned char)*text;
    if (c < 128) {
      for (int row = 0; row < 7; row++) {
        uint8_t bits = g_font[c][row];
        for (int col = 0; col < 5; col++) {
          if (bits & (0x10 >> col)) {
            int32_t px = x + col;
            int32_t py = y + row;
            if (px >= 0 && px < ui->width && py >= 0 && py < ui->height) {
              ui->put_pixel(ui->data, px, py, color);
            }
          }
        }
      }
    }
    x += 6;
    text++;
  }
}

static bool is_hovering_button(t_ui_ctx *ui, t_ui_button *btn) {
  const int32_t mx = ui->get_mouse_x(ui->data);
  const int32_t my = ui->get_mouse_y(ui->data);
  return (mx >= btn->base.x && mx < btn->base.x + btn->base.w &&
          my >= btn->base.y && my < btn->base.y + btn->base.h);
}

void ui_button(t_ui_ctx *ui, t_ui_button *btn) {
  const bool hovering = is_hovering_button(ui, btn);
  const bool pressed = ui->mouse_pressed(ui->data);
  const bool just_pressed = pressed && !ui->prev_mouse_down;
  const bool just_released = !pressed && ui->prev_mouse_down;

  btn->hovered = hovering;
  btn->clicked = false;

  // Handle click states
  if (just_pressed && hovering) {
    btn->held = true;
  }
  if (just_released) {
    if (btn->held && hovering) {
      btn->clicked = true;
    }
    btn->held = false;
  }

  // Determine target color
  uint32_t target_color = btn->color;
  if (btn->held && hovering) {
    target_color = btn->press_color;
  } else if (hovering) {
    target_color = btn->hover_color;
  }

  // Animate color transition
  btn->anim.state += (1.0f - btn->anim.state) * btn->anim.velocity;
  btn->base.color = lerp_u32(btn->base.color, target_color, btn->anim.velocity);

  // Draw button background
  ui_rect(ui, &btn->base);

  // Draw centered text
  if (btn->text) {
    int32_t text_len = (int32_t)strlen(btn->text);
    int32_t text_w = text_len * 6 - 1;
    int32_t text_h = 7;
    int32_t tx = btn->base.x + (btn->base.w - text_w) / 2;
    int32_t ty = btn->base.y + (btn->base.h - text_h) / 2;
    draw_text_at(ui, tx, ty, btn->text, btn->text_color);
  }
}
