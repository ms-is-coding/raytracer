static void draw_panel_text(t_ui_ctx *ui, int32_t x, int32_t y,
                             const char *text, uint32_t color) {
  while (*text) {
    unsigned char c = (unsigned char)*text;
    if (c < 128) {
      for (int row = 0; row < 7; row++) {
        uint8_t bits = g_font[c][row];
        for (int col = 0; col < 5; col++) {
          if (bits & (0x10 >> col)) {
            int32_t px = x + col;
            int32_t py = y + row;
            if (px >= 0 && px < ui->width && py >= 0 && py < ui->height) {
              ui->put_pixel(ui->data, px, py, color);
            }
          }
        }
      }
    }
    x += 6;
    text++;
  }
}

static bool is_in_title_bar(t_ui_ctx *ui, t_ui_panel *panel) {
  const int32_t mx = ui->get_mouse_x(ui->data);
  const int32_t my = ui->get_mouse_y(ui->data);
  const int32_t title_h = 20;

  return (mx >= panel->base.x && mx < panel->base.x + panel->base.w &&
          my >= panel->base.y && my < panel->base.y + title_h);
}

void ui_panel(t_ui_ctx *ui, t_ui_panel *panel) {
  const bool pressed = ui->mouse_pressed(ui->data);
  const bool just_pressed = pressed && !ui->prev_mouse_down;
  const bool just_released = !pressed && ui->prev_mouse_down;

  // Handle dragging
  if (panel->draggable) {
    if (just_pressed && is_in_title_bar(ui, panel)) {
      panel->dragging = true;
      panel->drag_offset_x = ui->get_mouse_x(ui->data) - panel->base.x;
      panel->drag_offset_y = ui->get_mouse_y(ui->data) - panel->base.y;
    }
    if (panel->dragging) {
      if (pressed) {
        panel->base.x = ui->get_mouse_x(ui->data) - panel->drag_offset_x;
        panel->base.y = ui->get_mouse_y(ui->data) - panel->drag_offset_y;
        // Clamp to screen bounds
        if (panel->base.x < 0) panel->base.x = 0;
        if (panel->base.y < 0) panel->base.y = 0;
        if (panel->base.x + panel->base.w > ui->width)
          panel->base.x = ui->width - panel->base.w;
        if (panel->base.y + panel->base.h > ui->height)
          panel->base.y = ui->height - panel->base.h;
      } else {
        panel->dragging = false;
      }
    }
  }

  // Draw panel background
  t_ui_base bg = panel->base;
  bg.color = panel->bg_color;
  ui_rect(ui, &bg);

  // Draw border
  if (panel->border_color != 0) {
    // Top border
    for (int32_t x = panel->base.x; x < panel->base.x + panel->base.w; x++) {
      ui->put_pixel(ui->data, x, panel->base.y, panel->border_color);
      ui->put_pixel(ui->data, x, panel->base.y + panel->base.h - 1, panel->border_color);
    }
    // Side borders
    for (int32_t y = panel->base.y; y < panel->base.y + panel->base.h; y++) {
      ui->put_pixel(ui->data, panel->base.x, y, panel->border_color);
      ui->put_pixel(ui->data, panel->base.x + panel->base.w - 1, y, panel->border_color);
    }
  }

  // Draw title bar
  if (panel->title) {
    t_ui_base title_bar = {
      .x = panel->base.x,
      .y = panel->base.y,
      .w = panel->base.w,
      .h = 20,
      .color = lerp_u32(panel->bg_color, 0xFFFFFF, 0.1f),
      .border = {.radius = panel->base.border.radius}
    };
    ui_rect(ui, &title_bar);

    // Draw title text
    draw_panel_text(ui, panel->base.x + 8, panel->base.y + 6,
                    panel->title, panel->title_color);

    // Draw separator line
    for (int32_t x = panel->base.x + 1; x < panel->base.x + panel->base.w - 1; x++) {
      ui->put_pixel(ui->data, x, panel->base.y + 19, panel->border_color);
    }
  }

  (void)just_released;
}
